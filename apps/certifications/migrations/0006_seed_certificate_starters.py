def seed_starters(apps, schema_editor):
    CertificateTemplate = apps.get_model("certifications", "CertificateTemplate")
    CertificateTemplateVersion = apps.get_model(
        "certifications",
        "CertificateTemplateVersion",
    )

    for starter in starter_definitions():
        existing = CertificateTemplate.objects.filter(
            is_starter=True,
            name=starter["name"],
        ).first()
        if existing:
            continue

        template = CertificateTemplate.objects.create(
            name=starter["name"],
            template_html="",
            visibility="system",
            status="published",
            is_starter=True,
            current_version_number=1,
            metadata={
                "builderSeedKey": starter["key"],
                "description": starter["description"],
                "seededBy": "certificate-builder-v1",
            },
        )
        CertificateTemplateVersion.objects.create(
            template=template,
            version_number=1,
            orientation=starter["orientation"],
            width_mm=starter["width"],
            height_mm=starter["height"],
            layout=starter["layout"],
            is_published=True,
        )


def remove_starters(apps, schema_editor):
    CertificateTemplate = apps.get_model("certifications", "CertificateTemplate")
    CertificateTemplate.objects.filter(
        is_starter=True,
        metadata__seededBy="certificate-builder-v1",
    ).delete()


