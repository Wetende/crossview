def element(
    element_id,
    element_type,
    x,
    y,
    width,
    height,
    content="",
    *,
    font_size=18,
    font_weight=400,
    color="#172033",
    align="center",
    z_index=1,
    **extra,
):
    custom_styles = extra.pop("styles", {})
    letter_spacing = extra.pop("letterSpacing", 0)
    styles = {
        "fontFamily": "Albert Sans",
        "fontSize": font_size,
        "fontWeight": font_weight,
        "color": color,
        "textAlign": align,
        "lineHeight": 1.2,
        "letterSpacing": letter_spacing,
    }
    styles.update(custom_styles)

    return {
        "id": element_id,
        "type": element_type,
        "x": x,
        "y": y,
        "width": width,
        "height": height,
        "rotation": 0,
        "locked": False,
        "hidden": False,
        "zIndex": z_index,
        "content": content,
        "styles": styles,
        **extra,
    }


